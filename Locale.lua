local fallbackLocale = locales.enUS

DDZ.locale = locales[currentLocale] and currentLocale or "enUS"

function DDZ.L(key, ...)
    local template = (locales[DDZ.locale] and locales[DDZ.locale][key]) or fallbackLocale[key] or key
    if select("#", ...) > 0 then
        return string.format(template, ...)
    end
    return template
end
